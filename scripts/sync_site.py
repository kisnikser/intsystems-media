"""Generate data/site/*.tex and avatars from a local clone of intsystems.github.io.

Run by hand before an event, after pulling the site repo:

    uv run --python 3.11 scripts/sync_site.py [--site ../intsystems.github.io]
"""

import argparse
import re
import shutil
import subprocess
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "data" / "site"
AVATARS = REPO / "assets" / "site-people"
SUPERVISORS = REPO / "data" / "supervisors.tex"
COURSE_TYPES = ("bachelor", "master")


def front_matter(path: Path) -> dict[str, str]:
    """Flat `key: value` pairs between the leading `---` lines."""
    text = path.read_text(encoding="utf-8")
    match = re.match(r"---\n(.*?)\n---", text, re.DOTALL)
    if not match:
        return {}
    pairs = {}
    for line in match[1].splitlines():
        key, sep, value = line.partition(":")
        if sep and not line.startswith((" ", "#")):
            pairs[key.strip()] = value.strip()
    return pairs


def i18n_section(path: Path, section: str) -> dict[str, str]:
    """`id: text` pairs of a top-level section such as `people:` in ru.yml."""
    pairs, inside = {}, False
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.startswith(" "):
            inside = line.rstrip() == f"{section}:"
            continue
        match = re.match(r"  (\w+):\s*(.*)$", line)
        if inside and match:
            pairs[match[1]] = match[2].strip().strip("'\"")
    return pairs


def tex(text: str) -> str:
    """Escape characters that break a macro argument."""
    return re.sub(r"([%#&_$])", r"\\\1", text)


def tex_url(url: str) -> str:
    """Escape only what `\\href` cannot take raw."""
    return re.sub(r"([%#])", r"\\\1", url)


def name_parts(name: str) -> tuple[str, str, str]:
    """Surname, given name, patronymic of a Russian full name."""
    surname, given, patronymic = (name.split(maxsplit=2) + ["", ""])[:3]
    return surname, given, patronymic


def site_version(site: Path) -> str:
    def git(*args: str) -> str:
        return subprocess.run(
            ["git", "-C", str(site), *args], capture_output=True, text=True, check=True
        ).stdout.strip()

    sha = git("rev-parse", "--short", "HEAD")
    status = git("status", "-sb").splitlines()[0]
    if "behind" in status or len(git("status", "--porcelain")) > 0:
        print(f"warning: site repo is not a clean, up-to-date checkout: {status}")
    return sha


def read_supervisors() -> list[str]:
    if not SUPERVISORS.exists():
        return []
    match = re.search(
        r"\\supervisors\{(.*?)\}", SUPERVISORS.read_text(encoding="utf-8"), re.DOTALL
    )
    return [s.strip() for s in match[1].split(",") if s.strip()] if match else []


def write(name: str, header: str, lines: list[str]) -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / name).write_text(header + "\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {(OUT / name).relative_to(REPO)}: {len(lines)} entries")


def yaml_scalars(path: Path) -> dict[str, str]:
    """Top-level scalar `key: value` pairs of a plain YAML file."""
    pairs = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        match = re.match(r"(\w+):\s*(.+)$", line)
        if match:
            pairs[match[1]] = match[2].strip().strip("'\"")
    return pairs


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--site", type=Path, default=REPO.parent / "intsystems.github.io"
    )
    site = parser.parse_args().site.resolve()

    sha = site_version(site)
    header = (
        f"% Generated by scripts/sync_site.py from intsystems.github.io@{sha}"
        ". Do not edit.\n"
    )
    names_ru = i18n_section(site / "_i18n" / "ru.yml", "people")
    courses_ru = i18n_section(site / "_i18n" / "ru.yml", "courses")

    people = {p.stem: front_matter(p) for p in sorted((site / "_people").glob("*.md"))}
    write(
        "people.tex",
        header,
        [
            f"\\siteperson{{{pid}}}{{{fm.get('position', '')}}}"
            + "".join(f"{{{tex(part)}}}" for part in name_parts(names_ru.get(pid, pid)))
            + f"{{{fm.get('avatar', '')}}}"
            for pid, fm in people.items()
        ],
    )

    courses = []
    for path in (site / "_course").glob("*.md"):
        fm = front_matter(path)
        if fm.get("type") in COURSE_TYPES:
            courses.append(
                (fm["type"], courses_ru.get(path.stem, path.stem), path.stem, fm)
            )
    courses.sort(key=lambda c: (COURSE_TYPES.index(c[0]), c[1]))
    instructors = sorted(
        {
            pid
            for *_, fm in courses
            for pid in fm.get("lecturers", "").split(",")
            if pid
        },
        key=lambda pid: names_ru.get(pid, pid),
    )
    write(
        "courses.tex",
        header,
        [
            f"\\sitecourse{{{cid}}}{{{ctype}}}{{{tex(name)}}}"
            f"{{{fm.get('lecturers', '')}}}{{{tex_url(fm.get('site', ''))}}}"
            for ctype, name, cid, fm in courses
        ]
        + [f"\\siteinstructors{{{','.join(instructors)}}}"],
    )

    stats = yaml_scalars(site / "_data" / "stats.yml")
    write(
        "stats.tex",
        header,
        [f"\\sitestat{{{k}}}{{{tex(v)}}}" for k, v in stats.items()],
    )

    copy_avatars(site, people, sorted(set(instructors) | set(read_supervisors())))


def copy_avatars(site: Path, people: dict[str, dict[str, str]], ids: list[str]) -> None:
    shutil.rmtree(AVATARS, ignore_errors=True)
    AVATARS.mkdir(parents=True)
    missing, total = [], 0
    for pid in ids:
        avatar = people.get(pid, {}).get("avatar", "")
        src = site / "images" / "people" / avatar
        if not avatar or not src.is_file():
            missing.append(pid)
            continue
        dst = AVATARS / avatar
        shutil.copy2(src, dst)
        total += dst.stat().st_size
    print(
        f"copied {len(ids) - len(missing)} avatars to {AVATARS.relative_to(REPO)}: {total / 2**20:.1f} MB"
    )
    if missing:
        print(f"warning: no avatar for {', '.join(missing)}")


if __name__ == "__main__":
    main()
